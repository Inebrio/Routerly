const FALLBACK: Mark = { color: '#64748b', text: '?' };

export function ClientLogo({ id, label, size = 36 }: { id: string; label: string; size?: number }) {
  const mark = MARKS[id] ?? FALLBACK;
  const text = mark.text ?? '';
  // Three-character marks need to shrink to stay inside the tile.
  const fontSize = text.length > 2 ? 30 : 38;

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 100 100"
      role="img"
      aria-label={`${label} logo`}
      style={{ flexShrink: 0, display: 'block' }}
    >
      {/* The hairline keeps near-black tiles from melting into a dark card. */}
      <rect
        x="1" y="1" width="98" height="98" rx="22"
        fill={mark.color}
        stroke="rgba(127,127,127,0.35)"
        strokeWidth="2"
      />
      {mark.glyph ? (
        // A nested viewport centres and scales any source box to 52 units, so
        // marks that are not 24x24 need no hand-computed transform.
        <svg x="24" y="24" width="52" height="52" viewBox={mark.glyph.box} fill="#ffffff">
          {mark.glyph.shapes}
        </svg>
      ) : (
        <text
          x="50"
          y="50"
          textAnchor="middle"
          dominantBaseline="central"
          fill="#ffffff"
          fontSize={fontSize}
          fontWeight="600"
          fontFamily="system-ui, sans-serif"
          letterSpacing="1"
        >
          {text}
        </text>
      )}
    </svg>
  );
}
